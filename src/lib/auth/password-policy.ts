import { ZxcvbnFactory } from "@zxcvbn-ts/core";
import {
  adjacencyGraphs,
  dictionary as common,
} from "@zxcvbn-ts/language-common";
import { dictionary as english, translations } from "@zxcvbn-ts/language-en";
import type { z } from "zod";
import {
  maxPasswordLength,
  newPasswordInput,
  normalizePassword,
} from "./password-input";

const estimator = new ZxcvbnFactory({
  dictionary: { ...common, ...english },
  graphs: adjacencyGraphs,
  translations,
  maxLength: maxPasswordLength * 2,
});

const commonPasswords = new Set([
  "admin",
  "administrator",
  "changeme",
  "default",
  "letmein",
  "login",
  "password",
  "passw0rd",
  "qwerty",
  "qwertyuiop",
  "welcome",
]);
const commonAffixes = new Set([...commonPasswords, "my", "welcometo"]);
const personalInfoAdvice =
  "Choose a passphrase unrelated to your name, company, or email address.";
const commonPasswordAdvice =
  "Avoid common passwords and predictable endings. Try several unrelated words.";
const passphraseAdvice =
  "Use several unrelated words or a password generated by your password manager.";

function matchingWords(value: string) {
  return (
    value
      .normalize("NFKC")
      .toLowerCase()
      .match(/[\p{L}\p{N}]+/gu) ?? []
  );
}

function withoutNumbers(value: string) {
  return value.replaceAll(/\p{N}/gu, "");
}

function basedOnTerm(basis: string, term: string) {
  if (term.length < 3) return false;
  if (basis === term) return true;
  return (
    (basis.startsWith(term) && commonAffixes.has(basis.slice(term.length))) ||
    (basis.endsWith(term) && commonAffixes.has(basis.slice(0, -term.length)))
  );
}

export function assessPassword(
  password: string,
  passwordTerms: readonly string[],
) {
  const parsed = newPasswordInput.safeParse(password);
  if (!parsed.success)
    return { score: 0, issue: parsed.error.issues[0].message };

  const value = normalizePassword(password).toLowerCase();
  const terms = ["fastmet", "fastmet fleet", ...passwordTerms].flatMap(
    (term) => {
      const words = matchingWords(term);
      return [term.toLowerCase(), words.join(""), ...words].filter(
        (word) => word.length >= 3,
      );
    },
  );
  const words = matchingWords(value).map(withoutNumbers).filter(Boolean);
  const basis = words.join("");
  if (!basis && !value.trim()) {
    return { score: 0, issue: "Use words or characters besides spaces." };
  }
  if (
    terms.some((term) =>
      basedOnTerm(basis, withoutNumbers(matchingWords(term).join(""))),
    )
  ) {
    return { score: 1, issue: personalInfoAdvice };
  }
  if (
    commonPasswords.has(basis) ||
    (words.length && words.every((word) => commonPasswords.has(word)))
  ) {
    return { score: 1, issue: commonPasswordAdvice };
  }

  const { score, sequence, feedback } = estimator.check(value, terms);
  if (score >= 3) return { score };

  if (
    sequence.some(
      (match) =>
        "dictionaryName" in match && match.dictionaryName === "userInputs",
    )
  ) {
    return { score, issue: personalInfoAdvice };
  }
  return { score, issue: feedback.warning || passphraseAdvice };
}

export function checkPasswordStrength(passwordTerms: readonly string[]) {
  return (
    { newPassword }: { newPassword: string },
    context: z.RefinementCtx,
  ) => {
    const { issue } = assessPassword(newPassword, passwordTerms);
    if (issue)
      context.addIssue({
        code: "custom",
        path: ["newPassword"],
        message: issue,
      });
  };
}
