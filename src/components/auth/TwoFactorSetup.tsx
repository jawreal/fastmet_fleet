"use client";
import { useCallback, useEffect, useState } from "react";
import { useForm } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";
import QRCode from "qrcode";
import { codeSchema, type CodeValues } from "@/lib/auth/schemas";
import type { TwoFactorSetup } from "@/lib/auth/types";
import { Button } from "@/components/ui/button";
import { AuthStep, type RunAuthAction } from "./AuthStep";
import {
  CodeField,
  StepHeader,
  SubmitButton,
  useCopy,
  useFormMessage,
} from "./FormParts";
function SetupForm({ run }: { run: RunAuthAction }) {
  const [setup, setSetup] = useState<TwoFactorSetup | null>(null);
  const [qr, setQr] = useState("");
  const [loading, setLoading] = useState(true);
  const [attempt, setAttempt] = useState(0);
  const message = useFormMessage();
  const report = message.report;
  const clipboard = useCopy();
  const form = useForm<CodeValues>({
    resolver: zodResolver(codeSchema),
    defaultValues: { code: "" },
  });

  // Fetch the key and generate the QR locally; secrets never go to a QR service.
  const load = useCallback(async () => {
    let result!: TwoFactorSetup;
    await run(async (adapter) => {
      result = await adapter.getTwoFactorSetup();
      return result.state;
    });
    const image = await QRCode.toDataURL(result.provisioningUri, {
      width: 208,
      margin: 4,
      errorCorrectionLevel: "M",
    });
    return { result, image };
  }, [run]);

  useEffect(() => {
    let active = true;
    load()
      .then(({ result, image }) => {
        if (active) {
          setSetup(result);
          setQr(image);
        }
      })
      .catch((error: unknown) => {
        if (active) report(error);
      })
      .finally(() => {
        if (active) setLoading(false);
      });
    return () => {
      active = false;
    };
  }, [load, attempt, report]);
  const busy = form.formState.isSubmitting;

  return (
    <div className="space-y-6">
      <StepHeader
        step="Account setup · 2 of 3"
        title="Set up Google Authenticator"
        description="Add your fleet account to Google Authenticator, then enter a code to confirm it's ready."
      />
      {message.alert}
      {loading ? (
        <p role="status" className="text-sm text-muted-foreground">
          Preparing your setup code…
        </p>
      ) : !setup ? (
        <Button
          variant="outline"
          onClick={() => {
            message.clear();
            setLoading(true);
            setAttempt((value) => value + 1);
          }}
        >
          Retry setup
        </Button>
      ) : (
        <>
          <ol className="list-decimal space-y-2 pl-4 text-xs leading-5 text-muted-foreground">
            <li>Open Google Authenticator and tap +.</li>
            <li>Choose “Scan a QR code”, or “Enter a setup key”.</li>
          </ol>
          {setup.demo && (
            <p className="rounded-md border p-3 text-xs leading-5 text-muted-foreground">
              Demo QR and key only. Do not use for real accounts. The mock
              accepts 012345, rather than codes generated by the app.
            </p>
          )}
          <div className="flex justify-center">
            <div
              role="img"
              aria-label="Google Authenticator setup QR code"
              className="size-52 rounded-md border bg-white"
              style={{
                backgroundImage: `url("${qr}")`,
                backgroundSize: "contain",
              }}
            />
          </div>
          <div className="space-y-2">
            <p className="text-xs font-medium">Manual setup key</p>
            <div className="flex items-center gap-2 rounded-md border p-2">
              <code className="min-w-0 flex-1 break-all text-xs">
                {setup.manualKey}
              </code>
              <Button
                variant="outline"
                type="button"
                onClick={() => void clipboard.copy(setup.manualKey)}
              >
                Copy key
              </Button>
            </div>
            <p className="text-xs text-muted-foreground">
              Choose a time-based key when entering it manually.
            </p>
            <p role="status" className="text-xs text-muted-foreground">
              {clipboard.feedback}
            </p>
          </div>
          <form
            noValidate
            aria-busy={busy}
            className="space-y-5"
            onSubmit={form.handleSubmit(async ({ code }) => {
              message.clear();
              try {
                await run((adapter) => adapter.confirmTwoFactorSetup(code));
                form.reset();
              } catch (error) {
                form.reset();
                message.report(error);
              }
            })}
          >
            <CodeField
              registration={form.register("code")}
              error={form.formState.errors.code?.message}
              busy={busy}
            />
            <SubmitButton busy={busy}>Confirm authenticator</SubmitButton>
          </form>
        </>
      )}
    </div>
  );
}
export function TwoFactorSetupStep() {
  return (
    <AuthStep expected="TWO_FACTOR_SETUP_REQUIRED">
      {(_, run) => <SetupForm run={run} />}
    </AuthStep>
  );
}
