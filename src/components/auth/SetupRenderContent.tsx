import { AuthFormSkeleton } from "./AuthFormSkeleton";
import type { TwoFactorSetup } from "@/lib/auth/types";
import { type RunAuthAction } from "./AuthStep";
import { useForm } from "react-hook-form";
import { type CodeValues } from "@/lib/auth/schemas";
import { CodeField, SubmitButton, useCopy, useFormMessage } from "./FormParts";
import { Button } from "../ui/button";

interface ISetupRenderContent {
  loading: boolean;
  setup: TwoFactorSetup | null;
  qr: string;
  busy: boolean;
  onRetry: () => void;
  run: RunAuthAction;
  form: ReturnType<typeof useForm<CodeValues>>;
  message: ReturnType<typeof useFormMessage>;
  clipboard: ReturnType<typeof useCopy>;
}

export default function SetupRenderContent(
  props: Readonly<ISetupRenderContent>,
) {
  if (props.loading) {
    return <AuthFormSkeleton fields={1} preparingSetup />;
  }

  if (!props.setup) {
    return (
      <Button variant="outline" onClick={props.onRetry}>
        Retry setup
      </Button>
    );
  }

  const handleSubmit = props.form.handleSubmit(async ({ code }) => {
    props.message.clear();

    try {
      await props.run((adapter) => adapter.confirmTwoFactorSetup(code));
      props.form.reset();
    } catch (error) {
      props.form.reset();
      props.message.report(error);
    }
  });

  return (
    <>
      <ol className="list-decimal space-y-2 pl-4 text-xs leading-5 text-muted-foreground">
        <li>Install or open Google Authenticator and tap +.</li>
        <li>Choose “Scan a QR code”, or “Enter a setup key”.</li>
      </ol>
      <p className="text-xs leading-5 text-muted-foreground">
        Scan once to add your FLEET account. Enter the six-digit code from the
        app below to finish setup. Future sign-ins use a new app code; you do
        not need to scan again unless your authenticator is reset.
      </p>

      {props.setup.demo && (
        <p className="rounded-md border p-3 text-xs leading-5 text-muted-foreground">
          Demo QR and key only. Do not use for real accounts. The mock accepts
          012345, rather than codes generated by the app.
        </p>
      )}

      <div className="flex justify-center">
        <div
          role="img"
          aria-label="Google Authenticator setup QR code"
          className="size-52 rounded-md border bg-white"
          style={{
            backgroundImage: `url("${props.qr}")`,
            backgroundSize: "contain",
          }}
        />
      </div>

      <div className="space-y-2">
        <p className="text-xs font-medium">Manual setup key</p>

        <div className="flex items-center gap-2 rounded-md border p-2">
          <code className="min-w-0 flex-1 break-all text-xs">
            {props.setup.manualKey}
          </code>

          <Button
            variant="outline"
            type="button"
            onClick={() => void props.clipboard.copy(props.setup!.manualKey)}
          >
            Copy key
          </Button>
        </div>

        <p className="text-xs text-muted-foreground">
          Choose a time-based key when entering it manually.
        </p>

        <p className="text-xs text-muted-foreground">
          {props.clipboard.feedback}
        </p>
      </div>

      <form
        noValidate
        aria-busy={props.busy}
        className="space-y-5"
        onSubmit={handleSubmit}
      >
        <CodeField
          registration={props.form.register("code")}
          error={props.form.formState.errors.code?.message}
          busy={props.busy}
        />

        <SubmitButton busy={props.busy}>Confirm authenticator</SubmitButton>
      </form>
    </>
  );
}
